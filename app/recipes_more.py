"""
recipes_more.py
---------------
WHY THIS FILE EXISTS (version 5.0 - "add at least 100 recipes"):
    80 more built-in recipes (Indian, Arabic, English, Italian, Asian, Mexican), on top of the 21 in
    seed_recipes.py. seed_recipes.py adds them to SEED_RECIPES, so the database, the catalogue
    exporter and the tests treat all 101 the same way.

    To keep 80 recipes readable, each one is a single R(...) call with short codes:
      meals     "B Br L S D"  = Breakfast, Brunch, Lunch, Snacks, Dinner
      tags      "HP LC LCal HF Bal" = High Protein, Low Carb, Low Calorie, High Fiber, Balanced
      machines  "Stove Oven" (any ONE is enough; "" = no cooking machine needed;
                 "RiceCooker" = Rice Cooker)
      ingredients "egg 3 pcs | onion 1 pcs | coriander 0.25 bunch ?"  (? = optional)
      nutrition  (protein g, carbs g, kcal) per serving - approximate.
"""

from app.models import Ingredient, Recipe

MEALS = {"B": "Breakfast", "Br": "Brunch", "L": "Lunch", "S": "Snacks", "D": "Dinner"}
TAGS = {"HP": "High Protein", "LC": "Low Carb", "LCal": "Low Calorie", "HF": "High Fiber",
        "Bal": "Balanced"}
MACHINES = {"Stove": "Stove", "Oven": "Oven", "Microwave": "Microwave", "RiceCooker": "Rice Cooker"}


def _ingredients(text):
    """'egg 3 pcs | coriander 0.25 bunch ?' -> [Ingredient('egg', 3, 'pcs'), Ingredient(..., optional=True)]"""
    result = []
    for part in text.split("|"):
        words = part.split()
        optional = words[-1] == "?"                       # a trailing ? marks an optional ingredient
        if optional:
            words = words[:-1]
        *name, quantity, unit = words                     # the last two words are amount and unit
        result.append(Ingredient(name=" ".join(name), quantity=float(quantity), unit=unit,
                                 optional=optional))
    return result


def R(name, cuisine, veg, minutes, servings, meals, tags, machines, ingredients, steps, nutrition):
    """One recipe from the short codes above."""
    protein, carbs, calories = nutrition
    return Recipe(name=name, cuisine=cuisine, is_veg=veg, prep_minutes=minutes, servings=servings,
                  meal_types=[MEALS[m] for m in meals.split()],
                  nutrition_tags=[TAGS[t] for t in tags.split()],
                  appliances=[MACHINES[m] for m in machines.split()],
                  ingredients=_ingredients(ingredients), steps=list(steps),
                  protein_g=protein, carbs_g=carbs, calories=calories)


